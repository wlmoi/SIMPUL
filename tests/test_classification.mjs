import assert from 'node:assert/strict';
import {classifyTrafficEvent,trafficClassSummary,makePoliceReviewBundle} from '../js/classification.js';
const make=(id,opts={})=>({id,type:'Jemput',zone:'Zona A',duration:30,at:'2026-11-15T10:00:00+07:00',source:'manual',vehicle:'Mobil',...opts});
const p1=make('m1',{pedestrianBlocked:'yes'});
assert.equal(classifyTrafficEvent(p1).priority,'P1');
assert.equal(classifyTrafficEvent(make('m2',{laneBlocked:'yes'})).priority,'P2');
assert.equal(classifyTrafficEvent(make('m3',{queueObserved:'yes'})).priority,'P2');
assert.equal(classifyTrafficEvent(make('m4',{type:'Menunggu',duration:130})).priority,'P3');
assert.equal(classifyTrafficEvent(make('m5',{type:'Menunggu',duration:119})).priority,'P4');
assert.equal(classifyTrafficEvent(make('m6',{zoneContext:'signed_no_stopping'})).ruleFlag,'unknown');
assert.equal(classifyTrafficEvent(make('m7',{zoneContext:'signed_no_stopping',signageVerified:true,evidenceReference:'ZONE-A-SIGN-1'})).ruleFlag,'review_rule');
assert.equal(classifyTrafficEvent(make('m8',{zoneContext:'signed_no_parking',signageVerified:true,evidenceReference:'ZONE-B-SIGN-1',type:'Jemput'})).ruleFlag,'interpretation_needed');
assert.equal(classifyTrafficEvent(make('m9',{laneBlocked:'no'})).impact.pedestrian,'unknown');
const observations=[p1,make('d1',{source:'demo',pedestrianBlocked:'yes'})];
const sum=trafficClassSummary(observations,{});
assert.equal(sum.manual,1);assert.equal(sum.synthetic,1);assert.equal(sum.priorities.P1,1);
const b=makePoliceReviewBundle({project:{id:'test',name:'Demo'},observations,eventReviews:{m1:{status:'context_reviewed',reviewer:'OFFICER-1',note:'sensitive note',at:'2026-11-15T11:00:00Z'}},classificationAudit:[{eventId:'m1',at:'2026-11-15T11:00:00Z',action:'update_status',reviewer:'OFFICER-1',status:'context_reviewed'}]});
assert.equal(b.records.length,1);assert.equal(b.records[0].legalConclusion,'NOT_DETERMINED');
assert.equal(JSON.stringify(b).includes('sensitive note'),false);
console.log('Traffic classification JS: 12 assertions passed');
