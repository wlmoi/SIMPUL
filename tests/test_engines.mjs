import assert from 'node:assert/strict';
import {forecast} from '../js/finance.js';
import {heuristicSimulation,observationStats} from '../js/analytics.js';
const base={sites:5,newSitesPerMonth:0,monthly:5_000_000,setup:35_000_000,pilots:0,pilotFee:20_000_000,churn:0,cloudMonthly:3_600_000,supportPerSite:550_000,implementationCostPerSite:11_500_000,pilotCost:9_000_000,fixedMonthly:8_500_000,salesMonthly:3_400_000};
const f=forecast(base);
assert.equal(f.revenue,475_000_000,'Five-site first year revenue must equal Rp475m');
assert.equal(f.mrr,25_000_000);
assert.equal(f.arr,300_000_000);
assert.equal(f.setupTotal,175_000_000);
assert.equal(f.recurringTotal,300_000_000);
assert.ok(f.net < f.revenue);
assert.equal(f.rows.length,12);
const growing=forecast({...base,newSitesPerMonth:2,pilots:2});
assert.ok(growing.revenue>f.revenue);
assert.ok(growing.costs>f.costs);
const scenario=heuristicSimulation({traffic:850,pickupShare:18,dwell:55,diversion:75,ruleDwell:20,pedestrianDetour:100});
assert.equal(scenario.engine,'heuristic');
assert.equal(scenario.valid,false);
assert.deepEqual(scenario.scenarios.map(s=>s.id),['A0','A1','A2']);
assert.ok(scenario.scenarios[1].delay<scenario.scenarios[0].delay);
assert.ok(scenario.scenarios[2].delay<scenario.scenarios[0].delay);
const obs=observationStats([{duration:15,type:'Jemput',source:'demo',zone:'Zona A'},{duration:45,type:'Turun',source:'manual',zone:'Zona B'}]);
assert.equal(obs.avgDwell,30);
assert.equal(obs.real,1);
console.log('PASS: business formulas, revenue audit, scenario heuristic distinction, observation aggregation');
