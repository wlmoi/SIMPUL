import assert from 'node:assert/strict';
import {initialData} from '../js/data.js';
import {actionableEvents,operationalBoard,validateCaseDraft,validateCaseUpdate,exportOperations} from '../js/operations.js';
const state=initialData();
assert.equal(actionableEvents(state).length,0,'Synthetic events must never appear as operational candidates');
state.observations.push({id:'p1',at:'2026-11-15T01:10:00Z',source:'manual',type:'Jemput',zone:'Zona A',duration:50,pedestrianBlocked:'yes'});
state.observations.push({id:'p2',at:'2026-11-15T01:20:00Z',source:'manual',type:'Menunggu',zone:'Zona B',duration:15,laneBlocked:'yes'});
state.observations.push({id:'p4',at:'2026-11-15T01:25:00Z',source:'manual',type:'Turun',zone:'Zona C',duration:10});
assert.equal(actionableEvents(state).length,2);
assert.throws(()=>validateCaseDraft({eventId:'evt-1001',owner:'Team',action:'Please check blockage'},state),/manual|P1\/P2/i);
assert.throws(()=>validateCaseDraft({eventId:'p4',owner:'Team',action:'Please check blockage'},state),/manual|P1\/P2/i);
assert.throws(()=>validateCaseDraft({eventId:'p1',owner:'Team',action:'short'},state),/10 karakter/);
const draft=validateCaseDraft({eventId:'p1',owner:'On-site team',action:'Review pedestrian path at observation zone',dueAt:'2030-01-01T12:00:00Z'},state);
assert.equal(draft.eventId,'p1');
state.responseCases.push({...draft,id:'case-1',status:'assigned',createdAt:'2026-11-15T02:00:00Z'});
assert.throws(()=>validateCaseDraft(draft,state),/sudah memiliki/);
const board=operationalBoard(state,new Date('2031-01-01T00:00:00Z'));
assert.equal(board.overdue,1);assert.equal(board.unassigned,1);assert.equal(board.open,1);
assert.throws(()=>validateCaseUpdate(state.responseCases[0],'resolved','done'),/10 karakter/);
assert.equal(validateCaseUpdate(state.responseCases[0],'resolved','Field team verified clearance').status,'resolved');
state.responseCases[0].status='resolved';
assert.equal(operationalBoard(state,new Date('2031-01-01T00:00:00Z')).overdue,0);
state.responseAudit.push({caseId:'case-1',eventId:'p1',at:'2026-11-15T02:05:00Z',status:'resolved',action:'status_change',reason:'sensitive details omitted'});
assert.equal(exportOperations(state).cases.length,1);
assert.equal(exportOperations(state).statusHistory.length,1);
assert.ok(!JSON.stringify(exportOperations(state)).includes('sensitive details omitted')); 
assert.equal(exportOperations(state).cases[0].legalConclusion,'NOT_DETERMINED');
assert.equal(JSON.stringify(exportOperations(state)).includes('evt-1001'),false,'Demo excluded from export');
assert.equal(exportOperations(state).cases[0].priority,'P1');
