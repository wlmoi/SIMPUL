import assert from 'node:assert/strict';
import {DEMO_STAGES,DEMO_SECONDS,DEMO_INPUTS,initialDemo,selectDemo,playDemo,advanceDemo} from '../js/demo-story.js';
import {getState} from '../js/store.js';
import {renderOverview} from '../js/views/overview.js';
import {orbitCamera,panCamera,zoomCamera} from '../js/viewer-controls.js';
const saved=JSON.stringify(getState());
const idle=initialDemo();
assert.equal(advanceDemo(idle,100),idle,'No autoplay before explicit Play');
let state=playDemo(idle);
assert.equal(advanceDemo(state,DEMO_SECONDS-0.1).index,0);
state=advanceDemo(state,DEMO_SECONDS);
assert.equal(state.index,1);
const paused=playDemo(state);
assert.equal(advanceDemo(paused,100),paused,'Pause freezes progress');
assert.equal(selectDemo(paused,-1),paused);
assert.equal(selectDemo(paused,6),paused);
assert.equal(selectDemo(paused,NaN),paused);
const selected=selectDemo(state,3);
assert.equal(selected.playing,false,'Manual exploration pauses auto-advance');
assert.equal(DEMO_STAGES[selected.index].scenario,'A1');
assert.equal(advanceDemo(state,Infinity),state);
const finished=advanceDemo(playDemo(idle),DEMO_SECONDS*DEMO_STAGES.length);
assert.equal(finished.complete,true);
assert.equal(finished.playing,false);
assert.equal(finished.index,5,'Stops at human evaluation, without looping');
assert.deepEqual(playDemo(finished),playDemo(idle),'Replay restarts the entire story');
assert.deepEqual(DEMO_STAGES.map(stage=>stage.scenario),['A0','A0','A0','A1','A2','A2']);
assert.equal(DEMO_INPUTS.seed,11);
const html=renderOverview();
assert.match(html,/data-action="home-demo-play"/);
assert.match(html,/data-demo-summary hidden/);
assert.match(html,/data-demo-progress/);
assert.equal((html.match(/class="demo-timeline"/g)||[]).length,1);
assert.equal(JSON.stringify(getState()),saved,'Playing the narrative and rendering do not change stored data');
const camera={yaw:0,pitch:0.4,dist:100,target:[0,0,0]};
orbitCamera(camera,40,10000);assert.ok(camera.pitch<Math.PI/2,'Orbit cannot flip the view upside down');
zoomCamera(camera,0.0001);assert.equal(camera.dist,25,'Near clipping is bounded');
zoomCamera(camera,10000);assert.equal(camera.dist,520,'Zooming out stays bounded');
zoomCamera(camera,NaN);assert.equal(camera.dist,520,'Invalid zoom is ignored');
panCamera(camera,1e6,-1e6);assert.ok(camera.target.every(Number.isFinite));
assert.ok(Math.abs(camera.target[0])<=350&&Math.abs(camera.target[2])<=140,'Panning stays near the schematic corridor');
assert.equal(JSON.stringify(getState()),saved,'Camera movement cannot change evidence');
console.log('PASS guided demo: explicit start, timed chapters, pause, exploration, completion, replay and unchanged stored evidence');
