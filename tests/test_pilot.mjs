import assert from 'node:assert/strict';
import {initialData} from '../js/data.js';
import {DEFAULT_PROTOCOL,normalizeProtocol,sessionQuality,surveyCoverage,exportSurveyCoverage} from '../js/pilot.js';

const state=initialData();
assert.equal(surveyCoverage(state).target,12,'Initial plan has 12 slots; this is an editable proposal-inspired assumption');
assert.equal(surveyCoverage(state).completed,0,'Demo observation must never fill field coverage');
assert.equal(surveyCoverage(state).rows.length,0);
assert.throws(()=>normalizeProtocol({replicates:0}),/tidak valid/);
assert.throws(()=>normalizeProtocol({minMinutes:61,maxMinutes:30}),/tidak valid/);
assert.deepEqual(DEFAULT_PROTOCOL.zones,['Zona A','Zona B','Zona C']);
const start='2026-11-15T01:00:00Z', end='2026-11-15T01:45:00Z';
const session={id:'s1',source:'manual',zone:'Zona A',period:'Jam sibuk',startedAt:start,endedAt:end};
state.sessions.push(session);
state.observations.push({id:'manual-evt',source:'manual',sessionId:'s1',at:'2026-11-15T01:04:00Z',zone:'Zona A',type:'Jemput',duration:50});
assert.equal(surveyCoverage(state).completed,0,'Unreviewed manual sessions are not accepted');
state.sessionReviews.s1={status:'approved',reviewer:'Survey coordinator',note:'Observer checked totals',at:'2026-11-15T03:00:00Z'};
assert.equal(surveyCoverage(state).completed,1);
assert.equal(surveyCoverage(state).slots.find(x=>x.zone==='Zona A'&&x.period==='Jam sibuk').completed,1);
assert.equal(surveyCoverage(state).surveyReady,false,'Single session is not study-ready');
assert.equal(exportSurveyCoverage(state).sessionAssessments[0].accepted,true);
state.sessions.push({...session,id:'s2',endedAt:'2026-11-15T01:20:00Z'});
state.sessionReviews.s2={...state.sessionReviews.s1};
assert.equal(surveyCoverage(state).completed,1,'20-minute session must not count');
state.sessions.push({...session,id:'s3',zone:'Zona A',period:'Jam sibuk'});
state.observations.push({id:'e3',source:'manual',sessionId:'s3',at:'2026-11-15T01:06:00Z',zone:'Zona A'});
state.sessionReviews.s3={...state.sessionReviews.s1};
assert.equal(surveyCoverage(state).completed,2);
state.sessions.push({...session,id:'s4'});
state.observations.push({id:'e4',source:'manual',sessionId:'s4',at:'2026-11-15T01:08:00Z',zone:'Zona A'});
state.sessionReviews.s4={...state.sessionReviews.s1};
assert.equal(surveyCoverage(state).completed,2,'Oversupply cannot compensate missing periods');
state.sessions.push({...session,id:'zero',zone:'Zona B',period:'Luar jam sibuk'});
state.sessionReviews.zero={status:'approved',reviewer:'Survey coordinator',note:'Verified zero vehicle activity',zeroConfirmed:true};
assert.equal(sessionQuality(state.sessions.at(-1),state.sessionReviews.zero,state.observations).accepted,true,'Reviewed zero-event window is allowed');
state.sessionReviews.zero.zeroConfirmed=false;
assert.equal(sessionQuality(state.sessions.at(-1),state.sessionReviews.zero,state.observations).accepted,false,'Silent zero data not accepted');
state.sessions.push({...session,id:'wrong'});
state.observations.push({id:'wrongEvt',source:'manual',sessionId:'wrong',at:'2026-11-15T04:00:00Z',zone:'Zona B'});
state.sessionReviews.wrong={...state.sessionReviews.s1};
assert.equal(sessionQuality(state.sessions.at(-1),state.sessionReviews.wrong,state.observations).accepted,false,'Cross-zone or out-of-window events invalidate quality');
console.log('PASS: synthetic exclusion, survey planning, review gate, duration bounds, stratum caps, zero-event confirmation and export');
