// Regenerates js/sim-readings-data.js from the traffic simulation (deterministic, ~5 s).
// Run after changing js/traffic-sim.js, js/fatmawati-layout.js or js/sim-readings.js.
import {writeFileSync} from 'node:fs';
const {computeSimReadings}=await import('../js/sim-readings.js');
const rows=computeSimReadings();
const body=rows.map(r=>'  '+JSON.stringify(r)).join(',\n');
writeFileSync(new URL('../js/sim-readings-data.js',import.meta.url),
`/** Generated by tools/gen_sim_readings.mjs from the SIMPUL traffic simulation. Do not edit by hand.
 * Interval data per zone, period and scenario; labelled source:'simulation', never field data. */
export const SIM_READINGS=Object.freeze([
${body}
].map(r=>Object.freeze(r)));
`);
console.log('PASS sim readings:',rows.length,'intervals');
